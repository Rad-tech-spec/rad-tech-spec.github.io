/**
 * Builds the agent's knowledge base from the site itself.
 *
 *   npm run agent:context     (run AFTER `nuxt generate`)
 *
 * Reads the generated HTML and writes agent/context.js — a plain string the
 * chat function embeds in its system prompt.
 *
 * Why parse the built HTML instead of importing data/author.js: that file
 * imports .svg files as Vue components, which Node can't resolve. Reading the
 * rendered output also guarantees the agent knows exactly what a visitor can
 * see — the two can't drift apart.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, ".output", "public");
const OUT = join(ROOT, "agent", "context.js");

const PAGES = [
  ["Home — intro, experience, and education", "index.html"],
  ["Projects", join("projects", "index.html")],
  ["Skills and credentials", join("skills", "index.html")],
  ["Blog posts (published on Medium)", join("blog", "index.html")],
];

function textFrom(html) {
  return html
    // Drop everything that isn't prose before stripping tags.
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<svg[\s\S]*?<\/svg>/gi, " ")
    .replace(/<!--[\s\S]*?-->/g, " ")
    // Keep block boundaries as line breaks so sections don't run together.
    .replace(/<\/(p|div|li|h[1-6]|section|article|tr)>/gi, "\n")
    .replace(/<[^>]+>/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#(\d+);/g, (_, d) => String.fromCharCode(+d))
    .replace(/&#x27;|&apos;/g, "'")
    .split("\n")
    .map((line) => line.replace(/\s+/g, " ").trim())
    .filter(Boolean)
    .join("\n");
}

if (!existsSync(DIST)) {
  console.error(`No build found at ${DIST}\nRun \`npx nuxt generate\` first.`);
  process.exit(1);
}

const sections = [];
for (const [label, file] of PAGES) {
  const path = join(DIST, file);
  if (!existsSync(path)) {
    console.warn(`skipped (not built): ${file}`);
    continue;
  }
  sections.push(`## ${label}\n\n${textFrom(readFileSync(path, "utf8"))}`);
}

const context = sections.join("\n\n---\n\n");

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `// GENERATED by scripts/build-agent-context.mjs — do not edit by hand.\n` +
    `// Rebuild with: npm run agent:context\n` +
    `export const SITE_CONTEXT = ${JSON.stringify(context)};\n`
);

const approxTokens = Math.round(context.length / 4);
console.log(`wrote ${OUT}`);
console.log(`  ${sections.length} sections, ${context.length} chars (~${approxTokens} tokens)`);
if (approxTokens < 512) {
  console.warn("  note: under 512 tokens — too short for prompt caching to engage.");
}
